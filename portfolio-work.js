function pinterestBoard(name, slug, images, coverIndex = 0, coverOptions = {}) {
  const galleryImages = images.map(([filename, width, height]) => ({
    src: `assets/portfolio/${slug}/${filename}`,
    width,
    height,
  }));

  return {
    name,
    slug,
    url: `https://mx.pinterest.com/myfurthur/${slug}/`,
    cover: galleryImages[coverIndex],
    coverOptions,
    previewImages: coverOptions.imageIndices?.map((index) => galleryImages[index]),
    images: galleryImages,
  };
}

